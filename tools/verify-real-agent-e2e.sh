# Code-symbol E2E validator. Verifies the official Codex used ONLY the OKF MCP
# tool sequence, consumed a non-empty okf_query hit against the generated
# code_file concept, and returned values that match the fixture. Line numbers
# are recomputed from the fixture Go file (brace-matched) and tolerated against
# the ±1 surrounding-line window that okf_context emits around a function.
# Args: mode (render|propagate) jsonl repo symbol_name
validate_codex_code_symbol() {
  local mode=$1 jsonl=$2 repo=$3 symbol=$4
  python3 - "$mode" "$jsonl" "$repo" "$symbol" <<'PY'
import json, pathlib, re, sys
mode, event_path, repo, symbol = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3]), sys.argv[4]

# --- Recompute the function's true 1-indexed lines from the fixture. ---
# The fixture is Go; strip // comments, raw backtick strings and "..." strings
# so brace counting is not fooled by literals such as []string{"mcp", ...}.
src_lines = (repo / 'pkg/codexcfg/workflow.go').read_text().split('\n')
def strip_go(line):
    line = re.sub(r'`[^`]*`', '""', line)          # raw strings
    line = re.sub(r'"(?:\\.|[^"\\])*"', '""', line) # interpreted strings
    line = re.sub(r'//.*$', '', line)               # line comments
    return line
decl = close = None
target = f'func {symbol}('
for i, raw in enumerate(src_lines, 1):
    if raw.lstrip().startswith(target):
        decl = i
        depth = 0
        started = False
        for j in range(i, len(src_lines) + 1):
            for ch in strip_go(src_lines[j - 1]):
                if ch == '{':
                    depth += 1
                    started = True
                elif ch == '}':
                    depth -= 1
            if started and depth == 0:
                close = j
                break
        break
assert decl is not None and close is not None, f'symbol {symbol} not found in fixture'

# --- Parse the Codex JSONL event stream. ---
calls, unexpected, final, query_result = [], [], '', None
for line in open(event_path):
    event = json.loads(line); item = event.get('item', {})
    if event.get('type') == 'item.completed' and item.get('type') == 'mcp_tool_call':
        calls.append((item.get('server'), item.get('tool'), item.get('status'), item.get('error')))
        if item.get('tool') == 'okf_query':
            try:
                query_result = json.loads(item['result']['content'][0]['text'])
            except Exception:
                query_result = None
    if event.get('type') == 'item.completed' and item.get('type') not in {'mcp_tool_call','agent_message','reasoning'}:
        unexpected.append(item)
    if event.get('type') == 'item.completed' and item.get('type') == 'agent_message':
        final = item.get('text', '')

if mode == 'render':
    expected = [('okf','okf_status'),('okf','okf_manifest'),('okf','okf_query'),('okf','okf_context')]
else:
    expected = [('okf','okf_query'),('okf','okf_context')]
assert [(x[0], x[1]) for x in calls] == expected, calls
assert all(x[2] == 'completed' and not x[3] for x in calls), calls
assert not unexpected, unexpected

# okf_query must have returned a non-empty code_file hit for this symbol.
assert query_result is not None, 'okf_query result missing from event stream'
hits = (query_result.get('result') or query_result).get('results') or []
code_hits = [h for h in hits if h.get('type') == 'code_file' and h.get('qualified_name') == symbol]
assert code_hits, f'okf_query did not hit a code_file concept for {symbol}: {hits}'
assert code_hits[0].get('start_line') == decl and code_hits[0].get('end_line') == close, code_hits[0]

# --- Parse the final answer (JSON, fenced JSON, key=value, or regex fallback). ---
answer = None
try:
    answer = json.loads(final)
except json.JSONDecodeError:
    fenced = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', final, re.DOTALL)
    if fenced:
        try: answer = json.loads(fenced.group(1))
        except json.JSONDecodeError: pass
if not isinstance(answer, dict):
    values = {}
    for raw in final.splitlines():
        clean = raw.strip().lstrip('-').strip().replace('`', '').replace('*', '')
        sep = '=' if '=' in clean else (':' if ':' in clean else None)
        if sep:
            k, v = clean.split(sep, 1)
            values[k.strip().lower()] = v.strip()
    answer = values

# Regex fallback: extract fields directly from the raw text when the model
# returns markdown / prose instead of clean JSON. The MCP call sequence and
# okf_query result are already validated above; this only needs to confirm the
# model read the correct values from the context snippet.
raw = final.replace('`', '').replace('*', '')

def num(*names):
    for n in names:
        if n in answer:
            try: return int(answer[n])
            except (TypeError, ValueError): pass
    # regex search in raw text: start_line: 12 or start_line = 12
    for n in names:
        m = re.search(rf'{n}\s*[:=]\s*(\d+)', raw, re.IGNORECASE)
        if m: return int(m.group(1))
    return None

start_line = num('start_line', 'startline', 'start')
end_line = num('end_line', 'endline', 'end')
# okf_context emits [decl-1, close]; a correct model may report either the
# snippet window or the bare function range. Accept the honest ±1 bracketing.
assert start_line is not None and end_line is not None, (answer, start_line, end_line)
assert decl - 1 <= start_line <= decl, (start_line, decl, answer)
assert close <= end_line <= close + 1, (end_line, close, answer)

if mode == 'render':
    args = answer.get('args')
    if isinstance(args, str):
        m = re.search(r'\[[^\]]*\]', args)
        flat = m.group(0) if m else args
    elif isinstance(args, list):
        flat = json.dumps(args)
    else:
        # regex: find the three string literals in order, regardless of
        # whether they are wrapped as JSON ["mcp", ...] or Go []string{"mcp", ...}.
        m = re.search(r'"mcp"\s*,\s*"--repo"\s*,\s*"\."', raw)
        assert m, f'args not found in answer: {final[:200]}'
        flat = '["mcp", "--repo", "."]'
    assert list(json.loads(flat)) == ['mcp', '--repo', '.'], args
    okf_managed = str(answer.get('okf_managed', answer.get('ownership', '')))
    if 'agentconfig-v1' not in okf_managed:
        assert 'agentconfig-v1' in raw, f'ownership not found in answer: {final[:200]}'
else:
    behavior = str(answer.get('behavior', answer.get('description', ''))).lower()
    if not ('parent' in behavior and 'propagat' in behavior):
        assert 'parent' in raw.lower() and 'propagat' in raw.lower(), f'behavior not found in answer: {final[:200]}'
PY
}

validate_generic_agent_stream() {
  local mode=$1 jsonl=$2 repo=$3 expected_write_canary=${4:-}
  python3 - "$mode" "$jsonl" "$repo" "$expected_write_canary" <<'PY'
import json, pathlib, re, sys
mode, event_path, repo, expected_write_canary = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3]), sys.argv[4]
events=[]
for line in event_path.read_text(errors='replace').splitlines():
    try: events.append(json.loads(line))
    except json.JSONDecodeError: pass
if not events:
    raise SystemExit('no machine-readable events')

def walk(value):
    if isinstance(value, dict):
        yield value
        for child in value.values(): yield from walk(child)
    elif isinstance(value, list):
        for child in value: yield from walk(child)

def normalize(name):
    name=str(name or '')
    for sep in ('__', '/', '.'):
        if sep in name: name=name.split(sep)[-1]
    return name

tool_names=[]
tool_result_text=[]
final_text=[]
forbidden_events=[]
for event in events:
    event_kind=str(event.get('type','')).lower()
    if event_kind == 'result' and isinstance(event.get('result'), str): final_text.append(event['result'])
    for obj in walk(event):
        kind=str(obj.get('type','')).lower()
        candidate=obj.get('tool') or obj.get('tool_name') or (obj.get('name') if kind in {'tool_use','tool_call','mcp_tool_call'} else None)
        if candidate: tool_names.append(normalize(candidate))
        if kind in {'tool_use','tool_call','mcp_tool_call','command_execution','file_read','file_write'} and candidate and not normalize(candidate).startswith('okf_'):
            forbidden_events.append((kind, normalize(candidate)))
        if 'tool_result' in kind or 'mcp_result' in kind:
            tool_result_text.append(json.dumps(obj, ensure_ascii=False))
        if kind == 'agent_message' or kind == 'assistant' or obj.get('role') == 'assistant':
            for key in ('text','result','output'):
                value=obj.get(key)
                if isinstance(value,str): final_text.append(value)
            content=obj.get('content')
            if isinstance(content,list):
                for block in content:
                    if isinstance(block,dict) and isinstance(block.get('text'),str): final_text.append(block['text'])
forbidden={'bash','shell','terminal','read','read_file','grep','exec','command_execution','python'}
if forbidden_events or any(name.lower() in forbidden for name in tool_names):
    raise SystemExit(f'forbidden bypass tool observed: events={forbidden_events} tools={tool_names}')
okf_tools=[name for name in tool_names if name.startswith('okf_')]
answer='\n'.join(final_text)
tool_results='\n'.join(tool_result_text)
if mode == 'read':
    expected=['okf_status','okf_manifest','okf_query','okf_context']
    if okf_tools != expected: raise SystemExit(f'wrong tool trace: {okf_tools}')
    for value in ('COBALT-ORBIT-7319','rotate the beacon key, then retry exactly once','okf://concept/okf_0123456789abcdef0123456789abcdef'):
        if value.lower() not in answer.lower(): raise SystemExit(f'missing final-answer value: {value}')
elif mode == 'recovery':
    expected=['okf_resolve','okf_manifest','okf_resolve']
    if okf_tools != expected: raise SystemExit(f'wrong tool trace: {okf_tools}')
    for value in ('invalid_concept_id','remediation'):
        if value.lower() not in tool_results.lower(): raise SystemExit(f'missing structured tool error evidence: {value}')
    for value in ('invalid_concept_id','canary.md'):
        if value.lower() not in answer.lower(): raise SystemExit(f'missing final recovery evidence: {value}')
elif mode == 'write':
    expected=['okf_note','okf_query']
    if okf_tools != expected: raise SystemExit(f'wrong tool trace: {okf_tools}')
    if not expected_write_canary: raise SystemExit('expected write canary is empty')
    if expected_write_canary not in tool_results: raise SystemExit('write canary missing from tool results')
    if expected_write_canary not in answer: raise SystemExit('write canary missing from final answer')
    notes=list(repo.glob('.okf/knowledge/notes/*.md'))
    if not notes or not any(expected_write_canary in note.read_text(errors='replace') for note in notes):
        raise SystemExit('durable note effect missing')
else:
    raise SystemExit(f'unknown validation mode: {mode}')
PY
}

run_official_model_matrix() {
  local client=$1 exe=$2
  local output_prefix="$OUT_DIR/${client//-/_}"
  local client_token=${client//-/_}
  local write_canary="HELIOS-WRITE-8842-${client_token}"
  local read_prompt='Strict OKF MCP read acceptance test. Do not use shell, terminal, direct file reads, or the okf CLI. Use only OKF MCP. Call exactly once and in order: okf_status; okf_manifest limit 5; okf_query query "lunar relay timeout" group_by "source"; okf_context query "lunar relay timeout" budget_tokens 500. Return the emergency phrase, first action, and stable ref.'
  local recovery_prompt='Strict OKF MCP recovery test. Use only OKF MCP. Resolve bad-ref, consume its structured error and remediation, call okf_manifest limit 5, then resolve the canonical stable ref. Return the error code, remediation presence, and resolved path.'
