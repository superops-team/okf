record() {
  local client=$1 layer=$2 status=$3 detail=$4
  printf '%s\t%s\t%s\t%s\n' "$client" "$layer" "$status" "$detail" >> "$results"
  case "$status" in
    PASS) pass=$((pass + 1)) ;;
    BLOCKED_*) blocked=$((blocked + 1)) ;;
    *) fail=$((fail + 1)) ;;
  esac
  printf '%-12s %-20s %-16s %s\n' "$client" "$layer" "$status" "$detail"
}

