// propagateParentIDs walks child nodes and copies each node's parent OKF id
// downward so children inherit parent IDs without mutating the source graph.
func propagateParentIDs(childIDs []string, parentOKFID string) []string {
	propagated := make([]string, 0, len(childIDs))
	for _, child := range childIDs {
		propagated = append(propagated, child, parentOKFID)
	}
	return propagated
}
